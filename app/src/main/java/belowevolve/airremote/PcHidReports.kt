package belowevolve.airremote

/** Report IDs and payloads match the composite keyboard/mouse descriptor. */
internal object PcHidReports {
    const val KEYBOARD = 1
    const val MOUSE = 2
    const val CONSUMER = 3
    val descriptor = intArrayOf(
        0x05,0x01, 0x09,0x06, 0xA1,0x01, 0x85,KEYBOARD,
        0x05,0x07, 0x19,0xE0, 0x29,0xE7, 0x15,0x00, 0x25,0x01,
        0x75,0x01, 0x95,0x08, 0x81,0x02,
        0x75,0x08, 0x95,0x01, 0x81,0x01,
        0x05,0x08, 0x19,0x01, 0x29,0x05, 0x75,0x01, 0x95,0x05, 0x91,0x02,
        0x75,0x03, 0x95,0x01, 0x91,0x01,
        0x05,0x07, 0x19,0x00, 0x29,0x65, 0x15,0x00, 0x25,0x65,
        0x75,0x08, 0x95,0x06, 0x81,0x00, 0xC0,
        0x05,0x01, 0x09,0x02, 0xA1,0x01, 0x85,MOUSE, 0x09,0x01, 0xA1,0x00,
        0x05,0x09, 0x19,0x01, 0x29,0x03, 0x15,0x00, 0x25,0x01,
        0x75,0x01, 0x95,0x03, 0x81,0x02,
        0x75,0x05, 0x95,0x01, 0x81,0x01,
        0x05,0x01, 0x09,0x30, 0x09,0x31, 0x09,0x38,
        0x15,0x81, 0x25,0x7F, 0x75,0x08, 0x95,0x03, 0x81,0x06, 0xC0,0xC0,
        0x05,0x0C, 0x09,0x01, 0xA1,0x01, 0x85,CONSUMER,
        0x15,0x00, 0x25,0x01, 0x75,0x01, 0x95,0x03, 0x09,0xE9, 0x09,0xEA, 0x09,0xE2, 0x81,0x02,
        0x75,0x05, 0x95,0x01, 0x81,0x01, 0xC0,
    ).map(Int::toByte).toByteArray()

    fun keyboard(key: Int = 0, modifiers: Int = 0) =
        byteArrayOf(modifiers.toByte(), 0, key.toByte(), 0, 0, 0, 0, 0)

    fun mouse(buttons: Int = 0, x: Int = 0, y: Int = 0, wheel: Int = 0) =
        byteArrayOf(
            (buttons and 7).toByte(),
            x.coerceIn(-127, 127).toByte(),
            y.coerceIn(-127, 127).toByte(),
            wheel.coerceIn(-127, 127).toByte(),
        )

    fun consumer(volumeUp: Boolean = false, volumeDown: Boolean = false, mute: Boolean = false) =
        byteArrayOf(((if (volumeUp) 1 else 0) or (if (volumeDown) 2 else 0) or (if (mute) 4 else 0)).toByte())
}
